//! Sealed deterministic generated-audio artifacts shared by offline engine services.

use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

use crate::{
    media::MAX_MEDIA_ASSET_BYTES,
    model::{GeneratedAssetProvenance, Unit},
};

use super::EngineError;

/// Exact portable format used by native generated-audio services.
pub const GENERATED_AUDIO_FORMAT: &str = "stereo_f32_wav";

/// Staged generated audio and its canonical source declaration.
///
/// Fields are private so external callers cannot forge provenance and then pass the artifact to a
/// checked publisher. Native generation services construct artifacts only after validating their
/// exact source Revision and request.
#[derive(Debug, Clone)]
pub struct GeneratedAudioArtifact {
    path: PathBuf,
    bytes: Vec<u8>,
    sha256: String,
    source_declaration: String,
    provenance: GeneratedAssetProvenance,
    sample_rate: u32,
    frame_count: u64,
}

impl GeneratedAudioArtifact {
    /// Returns the normalized Project-relative destination.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Returns the exact complete WAV bytes, which have not yet been published.
    pub fn bytes(&self) -> &[u8] {
        &self.bytes
    }

    /// Returns the SHA-256 of [`Self::bytes`].
    pub fn sha256(&self) -> &str {
        &self.sha256
    }

    /// Returns the canonical readable authoritative asset declaration.
    pub fn source_declaration(&self) -> &str {
        &self.source_declaration
    }

    /// Returns machine-readable provenance mirrored by the declaration.
    pub fn provenance(&self) -> &GeneratedAssetProvenance {
        &self.provenance
    }

    /// Returns the Project sample rate used by the WAV.
    pub const fn sample_rate(&self) -> u32 {
        self.sample_rate
    }

    /// Returns the complete generated frame count.
    pub const fn frame_count(&self) -> u64 {
        self.frame_count
    }
}

pub(crate) fn build_generated_audio_artifact(
    asset_id: &str,
    asset_name: &str,
    frames: &[[f32; 2]],
    sample_rate: u32,
    provenance: GeneratedAssetProvenance,
) -> Result<GeneratedAudioArtifact, EngineError> {
    if !valid_source_id(asset_id) {
        return Err(EngineError::Compile(
            "generated asset ID must start with an ASCII letter and contain only letters, digits, `_`, or `-`"
                .to_owned(),
        ));
    }
    if asset_name.trim().is_empty() || asset_name.chars().any(char::is_control) {
        return Err(EngineError::Compile(
            "generated asset name must be non-empty and contain no control characters".to_owned(),
        ));
    }
    if sample_rate == 0 {
        return Err(EngineError::Compile(
            "generated audio sample rate must be positive".to_owned(),
        ));
    }
    if provenance.format() != GENERATED_AUDIO_FORMAT {
        return Err(EngineError::Compile(format!(
            "generated audio format `{}` is unsupported",
            provenance.format()
        )));
    }
    let frame_count = u64::try_from(frames.len())
        .map_err(|_| EngineError::Compile("generated frame count does not fit u64".to_owned()))?;
    if provenance.expected_output_frames() != Some(frame_count) {
        return Err(EngineError::Compile(
            "generated frame count does not match its provenance".to_owned(),
        ));
    }
    if frames.iter().flatten().any(|sample| !sample.is_finite()) {
        return Err(EngineError::Compile(
            "generated audio contains a non-finite sample".to_owned(),
        ));
    }
    let byte_len = frame_count
        .checked_mul(8)
        .and_then(|bytes| bytes.checked_add(44))
        .ok_or_else(|| EngineError::Compile("generated byte count overflowed".to_owned()))?;
    if byte_len > MAX_MEDIA_ASSET_BYTES || byte_len > u64::from(u32::MAX) {
        return Err(EngineError::Compile(format!(
            "generated audio would produce {byte_len} bytes; maximum is {MAX_MEDIA_ASSET_BYTES}"
        )));
    }

    let path = PathBuf::from(format!("media/{asset_id}.wav"));
    let bytes = encode_float_wav(frames, sample_rate)?;
    let sha256 = hex_sha256(&bytes);
    let source_declaration = source_declaration(asset_id, asset_name, &path, &sha256, &provenance);
    Ok(GeneratedAudioArtifact {
        path,
        bytes,
        sha256,
        source_declaration,
        provenance,
        sample_rate,
        frame_count,
    })
}

pub(crate) fn encode_float_wav(
    frames: &[[f32; 2]],
    sample_rate: u32,
) -> Result<Vec<u8>, EngineError> {
    let data_len = u32::try_from(frames.len().saturating_mul(8))
        .map_err(|_| EngineError::Compile("generated WAV data exceeds RIFF limits".to_owned()))?;
    let riff_len = 36_u32
        .checked_add(data_len)
        .ok_or_else(|| EngineError::Compile("generated WAV RIFF length overflowed".to_owned()))?;
    let byte_rate = sample_rate
        .checked_mul(8)
        .ok_or_else(|| EngineError::Compile("generated WAV sample rate is too large".to_owned()))?;
    let mut bytes = Vec::with_capacity(data_len as usize + 44);
    bytes.extend_from_slice(b"RIFF");
    bytes.extend_from_slice(&riff_len.to_le_bytes());
    bytes.extend_from_slice(b"WAVEfmt ");
    bytes.extend_from_slice(&16_u32.to_le_bytes());
    bytes.extend_from_slice(&3_u16.to_le_bytes());
    bytes.extend_from_slice(&2_u16.to_le_bytes());
    bytes.extend_from_slice(&sample_rate.to_le_bytes());
    bytes.extend_from_slice(&byte_rate.to_le_bytes());
    bytes.extend_from_slice(&8_u16.to_le_bytes());
    bytes.extend_from_slice(&32_u16.to_le_bytes());
    bytes.extend_from_slice(b"data");
    bytes.extend_from_slice(&data_len.to_le_bytes());
    for frame in frames {
        bytes.extend_from_slice(&frame[0].to_le_bytes());
        bytes.extend_from_slice(&frame[1].to_le_bytes());
    }
    Ok(bytes)
}

fn source_declaration(
    id: &str,
    name: &str,
    path: &Path,
    sha256: &str,
    provenance: &GeneratedAssetProvenance,
) -> String {
    let header = format!(
        "asset {id} {} wav {} sha256 \"{sha256}\" {{\n",
        quote(name),
        quote(&path.to_string_lossy()),
    );
    let generated = match provenance {
        GeneratedAssetProvenance::Bounce {
            source_revision,
            owner,
            tap,
            start_frame,
            end_frame,
            tail_frames,
            format,
            algorithm,
            build,
        } => format!(
            "  generated {{\n    revision {}\n    owner {owner}\n    tap {tap}\n    range {start_frame} {end_frame}\n    tail {tail_frames}\n    format {format}\n    algorithm {algorithm}\n    build {}\n  }}\n",
            quote(source_revision),
            quote(build),
        ),
        GeneratedAssetProvenance::SampleTransform {
            source_revision,
            source_asset,
            source_sha256,
            source_start_frame,
            source_end_frame,
            output_frames,
            pitch_semitones,
            formants,
            quality,
            format,
            algorithm,
            deterministic_domain,
            build,
        } => format!(
            "  generated sample_transform {{\n    revision {}\n    source_asset {source_asset}\n    source_sha256 {}\n    source_range {source_start_frame} {source_end_frame}\n    output_frames {output_frames}\n    pitch {}\n    formants {formants}\n    quality {quality}\n    format {format}\n    algorithm {algorithm}\n    domain {}\n    build {}\n  }}\n",
            quote(source_revision),
            quote(source_sha256),
            Unit::Semitones.format_value(*pitch_semitones),
            quote(deterministic_domain),
            quote(build),
        ),
    };
    format!("{header}{generated}}}")
}

fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

pub(crate) fn valid_source_id(value: &str) -> bool {
    let mut characters = value.chars();
    characters
        .next()
        .is_some_and(|character| character.is_ascii_alphabetic())
        && characters.all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '-'
        })
}

fn hex_sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

#[cfg(test)]
mod tests {
    use std::io::Cursor;

    use super::*;

    #[test]
    fn float_wav_encoding_is_exact_and_reopenable() {
        let frames = [[0.25, -0.5], [1.0, -1.0], [0.0, 0.0]];
        let first = encode_float_wav(&frames, 48_000).expect("encode");
        let second = encode_float_wav(&frames, 48_000).expect("repeat encode");
        assert_eq!(first, second);
        let mut reader = hound::WavReader::new(Cursor::new(first)).expect("reopen WAV");
        assert_eq!(reader.spec().sample_format, hound::SampleFormat::Float);
        assert_eq!(reader.spec().channels, 2);
        assert_eq!(reader.duration(), 3);
        assert_eq!(
            reader
                .samples::<f32>()
                .collect::<Result<Vec<_>, _>>()
                .expect("samples"),
            frames.into_iter().flatten().collect::<Vec<_>>()
        );
    }
}
